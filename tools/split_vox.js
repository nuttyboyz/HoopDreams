// Splits src/vox.js into dist/vox.js + dist/vox2.js (each under the 16 MB published-file limit). Both files merge into one global VOX
// whichever loads first, so the artifact page can load them async.
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', 'src', 'vox.js'), 'utf8').split('\n');
const entries = src.filter(l => l.startsWith('"'));
// part 1 loads first: Shorty (voice 3, the default commentator), the players' call-outs and studio voice 0; part 2 has studio voices 1 and 2
const voiceOf = l => { const id = l.slice(1, l.indexOf('"', 1)); return id[0] === 'c' ? 'c' : id.split('.')[1]; };
const first = new Set(['3', 'c', '0']), parts = [entries.filter(l => first.has(voiceOf(l))), entries.filter(l => !first.has(voiceOf(l)))];
parts.forEach((p, i) => {
  const body = p.map(l => l.replace(/,$/, '')).join(',\n');
  fs.writeFileSync(path.join(__dirname, '..', 'dist', i ? 'vox2.js' : 'vox.js'), '/* Generated by tools/make_vox.py + tools/split_vox.js (part ' + (i + 1) + ' of 2). */\nvar VOX = Object.assign(window.VOX || {}, {\n' + body + '\n});\n');
});
console.log('vox split: ' + parts.map(p => p.length).join(' + ') + ' clips');
